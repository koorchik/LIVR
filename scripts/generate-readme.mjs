// Regenerates the implementations table in README.md from docs/data/implementations.json.
// Usage: node scripts/generate-readme.mjs [--check]
import fs from 'node:fs'

const README = new URL('../README.md', import.meta.url)
const DATA = new URL('../docs/data/implementations.json', import.meta.url)
const START = '<!-- implementations:start (generated by `npm run readme`, edit docs/data/implementations.json) -->'
const END = '<!-- implementations:end -->'

const REGISTRY_LABELS = {
  npm: 'npm',
  cpan: 'CPAN',
  packagist: 'Packagist',
  pypi: 'PyPI',
  go: 'Go',
  maven: 'Maven Central',
  rubygems: 'RubyGems',
  hex: 'Hex',
  luarocks: 'LuaRocks',
  raku: 'raku.land',
  cocoapods: 'CocoaPods'
}

const implementations = JSON.parse(fs.readFileSync(DATA, 'utf8'))

const rows = implementations.map((item) => {
  const name = item.name ? `${item.language} (${item.name})` : item.language
  const repo = new URL(item.repo).pathname.slice(1).replace(/\/$/, '')
  const pkg = item.package
    ? `[${REGISTRY_LABELS[item.package.registry] ?? item.package.registry}: \`${item.package.name}\`](${item.package.url})`
    : '—'
  const links = item.site ? `[${repo}](${item.repo}), [docs](${item.site})` : `[${repo}](${item.repo})`
  return `| ${name} | ${links} | ${pkg} | ${item.spec} | [@${item.maintainer.name}](${item.maintainer.url}) |`
})

const table = [
  '| Language | Repository | Package | LIVR | Maintainer |',
  '|---|---|---|---|---|',
  ...rows
].join('\n')

const readme = fs.readFileSync(README, 'utf8')
const startIndex = readme.indexOf(START)
const endIndex = readme.indexOf(END)
if (startIndex === -1 || endIndex === -1) {
  console.error(`README.md must contain the ${START} and ${END} markers`)
  process.exit(1)
}

const updated = `${readme.slice(0, startIndex + START.length)}\n${table}\n${readme.slice(endIndex)}`

if (process.argv.includes('--check')) {
  if (updated !== readme) {
    console.error('README.md is out of date. Run `npm run readme` and commit the result.')
    process.exit(1)
  }
  console.log('README.md is up to date.')
} else {
  fs.writeFileSync(README, updated)
  console.log('README.md updated.')
}
